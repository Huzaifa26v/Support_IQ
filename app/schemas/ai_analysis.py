# Import Any to support flexible source metadata.
from typing import Any

# Import Pydantic tools for request validation and response serialization.
from pydantic import BaseModel, Field

# ==========================================================
# 1. AI QUESTION REQUEST SCHEMA
# ==========================================================

class AIQuestionRequest(BaseModel):
    """
    Schema for customer questions submitted to AI assistance.

    Validates incoming questions before processing them.
    """

    # Customer question must contain at least 3 characters.
    question: str = Field(
        min_length=3,
        max_length=2000,
        description="Customer's support question.",
    )


# ==========================================================
# 2. AI ANSWER RESPONSE SCHEMA
# ==========================================================

class AIAnswerResponse(BaseModel):
    """
    Schema for the final AI-generated customer-support response.
    """

    # Original customer question.
    query: str

    # Answer generated by the language model.
    answer: str

    # Knowledge-base sources supporting the answer.
    # Store the retrieved knowledge-base source metadata.
    sources: list[dict[str, Any]]

    # Number of relevant knowledge-base chunks retrieved.
    total_results: int = Field(
        ge=0,
    )