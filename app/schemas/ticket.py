# Import datetime for ticket timestamps.
from datetime import datetime

# Import Literal to restrict priority to allowed values.
from typing import Literal

# Import Pydantic tools for validation and serialization.
from pydantic import BaseModel, ConfigDict, Field


# ==========================================================
# 1. TICKET CREATE SCHEMA
# ==========================================================

class TicketCreate(BaseModel):
    """
    Schema used when a customer creates a support ticket.

    It validates incoming ticket information before
    the application processes it.
    """

    # Ticket title must contain between 5 and 200 characters.
    title: str = Field(
        min_length=5,
        max_length=200,
    )

    # Detailed description of the customer's issue.
    description: str = Field(
        min_length=10,
    )

    # ID of the customer who is creating the ticket.
    # IDs must be positive integers.
    customer_id: int = Field(
        ge=1,
    )

    # Customers can select low, medium, or high priority.
    # Default priority is medium.
    priority: Literal["low", "medium", "high"] = "medium"


# ==========================================================
# 2. TICKET RESPONSE SCHEMA
# ==========================================================

class TicketResponse(BaseModel):
    """
    Schema used when returning ticket information through the API.

    It controls which ticket fields are visible in API responses.
    """

    # Unique ticket ID generated by the database.
    id: int

    # Short title of the support request.
    title: str

    # Detailed description of the issue.
    description: str

    # Current ticket status.
    status: str

    # Current ticket priority.
    priority: str

    # ID of the customer who owns this ticket.
    customer_id: int

    # Date and time when the ticket was created.
    created_at: datetime

    # Date and time when the ticket was last updated.
    updated_at: datetime

    # Allow Pydantic to read information directly
    # from SQLAlchemy model objects.
    model_config = ConfigDict(
        from_attributes=True,
    )